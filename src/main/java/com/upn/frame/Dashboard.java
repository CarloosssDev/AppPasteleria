    private <T extends JInternalFrame> T abrirInternalFrame(Class<T> claseFrame, boolean maximizar) {
        pnlBienvenida.setVisible(false);
        for (JInternalFrame frame : dpPanel.getAllFrames()) {
            if (claseFrame.isInstance(frame)) {
                try {
                    frame.setSelected(true);
                    frame.toFront();
                } catch (PropertyVetoException ignored) {
                }
                return (T) frame;
            }
        }
        for (JInternalFrame frame : dpPanel.getAllFrames()) {
            frame.dispose();
        }
        T nuevoFrame = context.getBean(claseFrame);
        dpPanel.add(nuevoFrame);

        nuevoFrame.setVisible(true);

        try {
            nuevoFrame.setSelected(true);
            if (maximizar) {
                nuevoFrame.setMaximum(true);
            } else {
                nuevoFrame.pack();
                int x = (dpPanel.getWidth() - nuevoFrame.getWidth()) / 2;
                int y = (dpPanel.getHeight() - nuevoFrame.getHeight()) / 2;
                nuevoFrame.setLocation(x, y);
            }
        } catch (PropertyVetoException e) {
            if (maximizar) {
                nuevoFrame.setSize(dpPanel.getSize());
            }
        }
        return nuevoFrame;
    }

    private void actualizarMenuActivo(JButton botonActivo) {
        Color colorActivo = Color.WHITE;
        Color colorInactivo = new Color(74, 53, 49);

        javax.swing.JButton[] botones = {btnInicio, btnVentas, btnProductos, btnCategorias, btnClientes, btnUsuarios};
        for (JButton btn : botones) {
            btn.setContentAreaFilled(false);
            btn.setForeground(colorInactivo);
            if (btn.getIcon() instanceof FontIcon icon) {
                icon.setIconColor(colorInactivo);
            }
        }

        botonActivo.setContentAreaFilled(true);
        botonActivo.setBackground(new Color(196, 117, 115));
        botonActivo.setForeground(colorActivo);
        if (botonActivo.getIcon() instanceof FontIcon icon) {
            icon.setIconColor(colorActivo);
        }
    }

    private void estilizarMenuVentas() {
        Color fondoCrema = new Color(255, 253, 252);
        Color bordeSuave = new Color(232, 218, 214);
        Color textoOscuro = new Color(74, 53, 49);
        Color hoverPastel = new Color(246, 236, 233);
        Color acentoTerracota = new Color(143, 86, 84);

        menuVentas.setBackground(fondoCrema);
        menuVentas.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(bordeSuave, 1),
                BorderFactory.createEmptyBorder(4, 4, 4, 4)
        ));
        menuVentas.setPopupSize(190, 84);

        itemNuevaVenta.setIcon(FontIcon.of(Feather.PLUS_CIRCLE, 16, acentoTerracota));
        itemReportesVentas.setIcon(FontIcon.of(Feather.BAR_CHART_2, 16, acentoTerracota));

        JMenuItem[] items = {itemNuevaVenta, itemReportesVentas};
        for (javax.swing.JMenuItem item : items) {
            item.setOpaque(true);
            item.setBackground(fondoCrema);
            item.setForeground(textoOscuro);
            item.setFont(new Font("Segoe UI", Font.BOLD, 12));
            item.setIconTextGap(10);
            item.setBorder(BorderFactory.createEmptyBorder(8, 12, 8, 12));
            item.setCursor(new Cursor(Cursor.HAND_CURSOR));

            item.addMouseListener(new java.awt.event.MouseAdapter() {
                @Override
                public void mouseEntered(java.awt.event.MouseEvent e) {
                    item.setBackground(hoverPastel);
                    item.setForeground(acentoTerracota);
                }

                @Override
                public void mouseExited(java.awt.event.MouseEvent e) {
                    item.setBackground(fondoCrema);
                    item.setForeground(textoOscuro);
                }
            });
        }
    }

    private void centrarBienvenida() {
        if (pnlBienvenida.isVisible()) {
            int x = (dpPanel.getWidth() - pnlBienvenida.getWidth()) / 2;
            int y = (dpPanel.getHeight() - pnlBienvenida.getHeight()) / 2;
            pnlBienvenida.setLocation(Math.max(0, x), Math.max(0, y));
        }
    }
