    public void setEmpleadoLogueado(Empleado empleado) {
        this.empleadoLogueado = empleado;

        if (empleado != null) {
            boolean esAdmin = (empleado.getRol() == Rol.Administrador);
            btnUsuarios.setVisible(esAdmin);

            lblNombreEmpleado.setText(empleado.mostrarNombreCompleto());
            lblRolEmpleado.setText(empleado.getRol().name());

            if (btnUsuarios.getParent() != null) {
                btnUsuarios.getParent().revalidate();
                btnUsuarios.getParent().repaint();
            }
        }
    }

    public Empleado getEmpleadoLogueado() {
        return empleadoLogueado;
    }

