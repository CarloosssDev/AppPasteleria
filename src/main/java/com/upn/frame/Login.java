    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed

        String dni = txtDni.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        if (dni.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingresa el DNI.", "Campo requerido",
                    JOptionPane.WARNING_MESSAGE);
            txtDni.requestFocus();
            return;
        }

        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingresa la contraseña.", "Campo requerido",
                    JOptionPane.WARNING_MESSAGE);
            txtPassword.requestFocus();
            return;
        }

        Empleado empleado = empleadoService.buscarEmpleado(dni);

        if (empleado == null) {
            JOptionPane.showMessageDialog(this, "El DNI ingresado no corresponde a ningún empleado registrado.",
                    "Acceso Denegado", JOptionPane.ERROR_MESSAGE);
            txtDni.selectAll();
            txtDni.requestFocus();
            return;
        }

        if (empleado.getPassword().equals(password)) {
            JOptionPane.showMessageDialog(this,
                    "¡Bienvenido(a) " + empleado.getNombre() + "!\nRol: " + empleado.getRol(),
                    "Acceso Concedido",
                    JOptionPane.INFORMATION_MESSAGE);

            Dashboard dash = context.getBean(Dashboard.class);
            dash.setEmpleadoLogueado(empleado);
            dash.setVisible(true);

            this.dispose();

        } else {
            JOptionPane.showMessageDialog(this, "Contraseña incorrecta.", "Acceso Denegado", JOptionPane.ERROR_MESSAGE);
            txtPassword.setText("");
            txtPassword.requestFocus();
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

    private void txtDniKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtDniKeyPressed
        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
            String dniIngresado = txtDni.getText().trim();

            if (dniIngresado.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor, ingresa un número de DNI.", "Advertencia",
                        JOptionPane.WARNING_MESSAGE);
                txtNombreCompleto.setText("");
                return;
            }

            // Buscar el empleado mediante la capa de servicio
            Empleado empleado = empleadoService.buscarEmpleado(dniIngresado);

            if (empleado != null) {
                txtNombreCompleto.setText(empleado.mostrarNombreCompleto());
                txtPassword.requestFocus();
            } else {
                txtNombreCompleto.setText("");
                JOptionPane.showMessageDialog(this,
                        "No se encontró ningún empleado registrado con el DNI: " + dniIngresado,
                        "Empleado no encontrado", JOptionPane.ERROR_MESSAGE);
                txtDni.selectAll();
                txtDni.requestFocus();
            }
        }
    }//GEN-LAST:event_txtDniKeyPressed

    private void txtPasswordKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPasswordKeyPressed
        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
            if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
                String password = new String(txtPassword.getPassword()).trim();

                if (!password.isEmpty()) {
                    btnIngresarActionPerformed(null);
                } else {
                    JOptionPane.showMessageDialog(this,
                            "Por favor, ingresa tu contraseña.",
                            "Advertencia",
                            JOptionPane.WARNING_MESSAGE);
                }
            }
        }
    }//GEN-LAST:event_txtPasswordKeyPressed

