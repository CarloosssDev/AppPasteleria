    private void configurarTablaUsuarios() {
        String[] columnas = {"ID", "DNI", "Nombre Completo", "Teléfono", "Rol", "Estado"};
        modeloUsuarios = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblUsuarios.setModel(modeloUsuarios);
    }

    private void cargarTodosLosUsuarios() {
        try {
            List<Empleado> lista = service.listarTodos();
            llenarTablaUsuarios(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar usuarios: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void aplicarFiltrosCombinados() {
        try {
            Rol rolSeleccionado = null;
            if (cboFiltroRol.getSelectedIndex() > 0 && cboFiltroRol.getSelectedItem() != null) {
                rolSeleccionado = Rol.valueOf(cboFiltroRol.getSelectedItem().toString());
            }

            Boolean estado = null;
            int indexEstado = cboEstado.getSelectedIndex();
            if (indexEstado == 1) {
                estado = true;
            } else if (indexEstado == 2) {
                estado = false;
            }

            String texto = txtBuscar.getText().trim();
            List<Empleado> lista = service.filtrarEmpleados(rolSeleccionado, estado, texto);
            llenarTablaUsuarios(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al filtrar usuarios: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void llenarTablaUsuarios(List<Empleado> lista) {
        modeloUsuarios.setRowCount(0);

        for (Empleado e : lista) {
            Object[] fila = new Object[]{
                e.getId(),
                e.getDni(),
                e.mostrarNombreCompleto(),
                e.getTelefono(),
                e.getRol().name(),
                e.isEstado() ? "Activo" : "Inactivo"
            };
            modeloUsuarios.addRow(fila);
        }
    }

    private void cargarUsuarioEnFormulario(Long idEmpleado) {
        try {
            Empleado e = service.buscarPorId(idEmpleado);
            if (e != null) {
                txtId.setText(String.valueOf(e.getId()));
                txtDni.setText(e.getDni());
                txtNombre.setText(e.getNombre());
                txtApellido.setText(e.getApellido());
                txtTelefono.setText(e.getTelefono());
                txtPassword.setText(e.getPassword());
                cboRol.setSelectedItem(e.getRol().name());
                cbEstado.setSelected(e.isEstado());

                esEdicion = true;
                habilitarFormulario(true);
                boolean esMismoUsuario = (empleadoLogueado != null && empleadoLogueado.getId().equals(e.getId()));
                cboRol.setEnabled(!esMismoUsuario);
                cbEstado.setEnabled(!esMismoUsuario);

                txtDni.requestFocus();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al obtener datos del usuario: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpiarFormulario() {
        txtId.setText("");
        txtDni.setText("");
        txtNombre.setText("");
        txtApellido.setText("");
        txtTelefono.setText("");
        txtPassword.setText("");
        if (cboRol.getItemCount() > 0) {
            cboRol.setSelectedIndex(0);
        }
        cbEstado.setSelected(true);
    }

    private void habilitarFormulario(boolean habilitar) {
        txtDni.setEnabled(habilitar);
        txtNombre.setEnabled(habilitar);
        txtApellido.setEnabled(habilitar);
        txtTelefono.setEnabled(habilitar);
        txtPassword.setEnabled(habilitar);
        cboRol.setEnabled(habilitar);
        cbEstado.setEnabled(habilitar);

        btnGuardar.setEnabled(habilitar);
        btnCancelar.setEnabled(habilitar);

        btnNuevo.setEnabled(!habilitar);
        btnEditar.setEnabled(!habilitar);
        btnEliminar.setEnabled(!habilitar);
        tblUsuarios.setEnabled(!habilitar);
    }

    private void estadoInicialFormulario() {
        limpiarFormulario();
        habilitarFormulario(false);
        esEdicion = false;
    }

