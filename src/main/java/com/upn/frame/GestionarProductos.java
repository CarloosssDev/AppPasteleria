    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnGuardarActionPerformed
        String nombre = txtNombre.getText().trim();
        String precioStr = txtPrecio.getText().trim();
        Object catSeleccionada = cboCategoria.getSelectedItem();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre del producto es obligatorio.", "Validación",
                    JOptionPane.WARNING_MESSAGE);
            txtNombre.requestFocus();
            return;
        }

        if (precioStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El precio base es obligatorio.", "Validación",
                    JOptionPane.WARNING_MESSAGE);
            txtPrecio.requestFocus();
            return;
        }

        double precio;
        try {
            precioStr = precioStr.replace(",", ".");
            precio = Double.parseDouble(precioStr);
            if (precio <= 0) {
                JOptionPane.showMessageDialog(this, "El precio debe ser mayor a 0.", "Validación",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un precio numérico válido (ejemplo: 45.50).", "Validación",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!(catSeleccionada instanceof Categoria)) {
            JOptionPane.showMessageDialog(this, "Seleccione una categoría válida.", "Validación",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        Categoria categoria = (Categoria) catSeleccionada;
        int stock = (int) spnStock.getValue();

        try {
            ProductoPasteleria producto;

            if (esEdicion) {
                Long id = Long.parseLong(txtId.getText());
                producto = productoService.buscarPorId(id);
                producto.setNombre(nombre);
                producto.setPrecioBase(precio);
                producto.setStock(stock);
                producto.setCategoria(categoria);
                producto.setEstado(cbEstado.isSelected());
            } else {
                producto = new ProductoPasteleria();
                producto.setNombre(nombre);
                producto.setPrecioBase(precio);
                producto.setStock(stock);
                producto.setCategoria(categoria);
                producto.setEstado(cbEstado.isSelected());
            }

            productoService.guardar(producto);

            JOptionPane.showMessageDialog(this,
                    esEdicion ? "Producto actualizado correctamente." : "Producto registrado correctamente.");
            cargarTodosLosProductos();
            estadoInicialFormulario();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar el producto: " + e.getMessage(), "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

