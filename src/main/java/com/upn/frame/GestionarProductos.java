    private void cargarCategorias(JComboBox<Object> cbo, boolean agregarOpcionTodas) {
        try {
            cbo.removeAllItems();

            if (agregarOpcionTodas) {
                Categoria opcionTodas = new Categoria();
                opcionTodas.setId(0L);
                opcionTodas.setNombre("-- Todas las Categorías --");

                cbo.addItem(opcionTodas);
            }

            List<Categoria> lista = categoriaService.listarTodas();

            for (Categoria cat : lista) {
                cbo.addItem(cat);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar categorías: " + e.getMessage());
        }
    }

    private void cargarTodosLosProductos() {
        try {
            List<ProductoPasteleria> lista = productoService.listarTodos();
            llenarTablaProductos(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar productos: " + e.getMessage());
            e.printStackTrace();
        }
    }

    private void aplicarFiltrosCombinados() {
        try {
            Long idCategoria = 0L;
            Object itemCat = cboCategoriasFiltrar.getSelectedItem();
            if (itemCat instanceof Categoria) {
                idCategoria = ((Categoria) itemCat).getId();
            }

            Boolean estado = null;
            int indexEstado = cboEstado.getSelectedIndex();
            if (indexEstado == 1) {
                estado = true;
            } else if (indexEstado == 2) {
                estado = false;
            }

            String textoBusqueda = txtBuscar.getText().trim();

            List<ProductoPasteleria> lista = productoService.filtrarProductosCombinados(idCategoria, estado, textoBusqueda);

            llenarTablaProductos(lista);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al filtrar productos: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void llenarTablaProductos(List<ProductoPasteleria> lista) {
        modeloProductos.setRowCount(0);

        for (ProductoPasteleria p : lista) {
            Object[] fila = new Object[]{
                p.getId(),
                p.getNombre(),
                p.getCategoria().getNombre(),
                String.format("S/ %.2f", p.getPrecioBase()),
                p.getStock(),
                p.isEstado() ? "Activo" : "Inactivo"
            };
            modeloProductos.addRow(fila);
        }
    }

    private void cargarProductoEnFormulario(Long idProducto) {
        try {
            ProductoPasteleria p = productoService.buscarPorId(idProducto);

            if (p != null) {
                txtId.setText(String.valueOf(p.getId()));
                txtNombre.setText(p.getNombre());
                txtPrecio.setText(String.valueOf(p.getPrecioBase()));
                spnStock.setValue(p.getStock());
                cbEstado.setSelected(p.isEstado());

                for (int i = 0; i < cboCategoria.getItemCount(); i++) {
                    Object item = cboCategoria.getItemAt(i);
                    if (item instanceof Categoria) {
                        Categoria cat = (Categoria) item;
                        if (cat.getId().equals(p.getCategoria().getId())) {
                            cboCategoria.setSelectedIndex(i);
                            break;
                        }
                    }
                }

                esEdicion = true;
                habilitarFormulario(true);
                txtNombre.requestFocus();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al obtener datos del producto: " + e.getMessage());
        }
    }

    private void limpiarFormulario() {
        txtId.setText("");
        txtNombre.setText("");
        txtPrecio.setText("");
        spnStock.setValue(0);
        cbEstado.setSelected(true);
        if (cboCategoria.getItemCount() > 0) {
            cboCategoria.setSelectedIndex(0);
        }
    }

    private void habilitarFormulario(boolean habilitar) {
        txtNombre.setEnabled(habilitar);
        txtPrecio.setEnabled(habilitar);
        spnStock.setEnabled(habilitar);
        cboCategoria.setEnabled(habilitar);
        cbEstado.setEnabled(habilitar);

        btnGuardar.setEnabled(habilitar);
        btnCancelar.setEnabled(habilitar);

        btnNuevo.setEnabled(!habilitar);
        btnEditar.setEnabled(!habilitar);
        btnEliminar.setEnabled(!habilitar);
        tblProductos.setEnabled(!habilitar);
    }

    private void estadoInicialFormulario() {
        limpiarFormulario();
        habilitarFormulario(false);
        esEdicion = false;
    }

    private void configurarTablaProductos() {
        String[] columnas = {"ID", "Nombre", "Categoria", "Precio Base", "Stock", "Estado"};
        modeloProductos = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblProductos.setModel(modeloProductos);
    }

