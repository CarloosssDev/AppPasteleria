    private void buscarCliente() {
        String dni = txtDniCliente.getText().trim();

        // 1. Validar que no esté vacío
        if (dni.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Por favor, ingrese un número de DNI.",
                    "Advertencia",
                    JOptionPane.WARNING_MESSAGE);
            txtDniCliente.requestFocus();
            return;
        }

        // 2. Validar formato (ejemplo: 8 dígitos numéricos)
        if (!dni.matches("\\d{8}")) {
            JOptionPane.showMessageDialog(this,
                    "El DNI debe contener exactamente 8 dígitos numéricos.",
                    "DNI Inválido",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            Cliente cliente = clienteService.buscarPorDni(dni);

            if (cliente != null) {
                lblNombreCliente.setText("Cliente: " + cliente.mostrarNombreCompleto());

                this.clienteSeleccionado = cliente;
            } else {
                lblNombreCliente.setText("Cliente: [No Encontrado]");
                lblNombreCliente.setForeground(java.awt.Color.RED);
                this.clienteSeleccionado = null;

                JOptionPane.showMessageDialog(this,
                        "No se encontró ningún cliente registrado con el DNI: " + dni,
                        "Cliente No Encontrado",
                        JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Error al conectar con la base de datos: " + e.getMessage(),
                    "Error de Conexión",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

