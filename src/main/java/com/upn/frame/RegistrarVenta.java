    private void cargarProductosPorNombre(String nombre) {
        try {
            List<ProductoPasteleria> lista = productoService.buscarPorNombre(nombre);
            llenarTablaProductos(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al buscar productos: " + e.getMessage());
        }
    }

    private void cargarProductosPorCategoriaId(Long idCategoria) {
        try {
            List<ProductoPasteleria> lista = productoService.listarPorCategoria(idCategoria);
            llenarTablaProductos(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al filtrar productos: " + e.getMessage());
        }
    }

    private void llenarTablaProductos(List<ProductoPasteleria> lista) {
        modeloProductos.setRowCount(0);

        for (ProductoPasteleria p : lista) {
            Object[] fila = new Object[]{
                p.getId(),
                p.getNombre(),
                String.format("S/ %.2f", p.getPrecioBase()),
                p.getStock()
            };
            modeloProductos.addRow(fila);
        }
    }

    private void buscarCliente() {
        String dni = txtDniCliente.getText().trim();

        if (dni.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Por favor, ingrese un número de DNI.",
                    "Advertencia",
                    JOptionPane.WARNING_MESSAGE);
            txtDniCliente.requestFocus();
            return;
        }

        if (!dni.matches("\\d{8}")) {
            JOptionPane.showMessageDialog(this,
                    "El DNI debe contener exactamente 8 dígitos numéricos.",
                    "DNI Inválido",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            Cliente cliente = clienteService.buscarPorDni(dni);

            if (cliente != null) {
                lblNombreCliente.setText("Cliente: " + cliente.mostrarNombreCompleto());
                lblNombreCliente.setForeground(Color.BLACK);

                this.clienteSeleccionado = cliente;
            } else {
                lblNombreCliente.setText("Cliente: [No Encontrado]");
                lblNombreCliente.setForeground(Color.RED);
                this.clienteSeleccionado = null;

                JOptionPane.showMessageDialog(this,
                        "No se encontró ningún cliente registrado con el DNI: " + dni,
                        "Cliente No Encontrado",
                        JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Error al conectar con la base de datos: " + e.getMessage(),
                    "Error de Conexión",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

