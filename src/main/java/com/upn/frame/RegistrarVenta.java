    private void btnProcesarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcesarVentaActionPerformed
        if (this.clienteSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Debe buscar y seleccionar un cliente por DNI.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (modeloCarrito.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "El carrito está vacío.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        List<DetalleVenta> listaDetalles = new ArrayList<>();
        for (int i = 0; i < modeloCarrito.getRowCount(); i++) {
            Long idProducto = Long.parseLong(modeloCarrito.getValueAt(i, 0).toString());
            int cantidad = Integer.parseInt(modeloCarrito.getValueAt(i, 2).toString());

            String precioStr = modeloCarrito.getValueAt(i, 3).toString().replace("S/ ", "").replace(",", ".");
            double precioUnitario = Double.parseDouble(precioStr);

            String subtotalStr = modeloCarrito.getValueAt(i, 4).toString().replace("S/ ", "").replace(",", ".");
            double subtotal = Double.parseDouble(subtotalStr);
            ProductoPasteleria p = new ProductoPasteleria();
            p.setId(idProducto);

            DetalleVenta detalle = new DetalleVenta();
            detalle.setProducto(p);
            detalle.setCantidad(cantidad);
            detalle.setPrecioUnitario(precioUnitario);
            detalle.setSubtotal(subtotal);

            listaDetalles.add(detalle);
        }

        double totalFinal = 0.0;
        double total = Double.parseDouble(lblTotal.getText().replace("S/ ", "").replace(",", "."));
        totalFinal += total;
        double adelanto = Double.parseDouble(txtAdelanto.getText().trim().replace(",", "."));
        double saldo = total - adelanto;

        try {
            Venta ventaGuardada = ventaService.procesarVenta(this.clienteSeleccionado, this.empleadoLogueado, listaDetalles, totalFinal, adelanto, saldo);

            JOptionPane.showMessageDialog(this,
                    "¡Venta N° " + ventaGuardada.getId() + " registrada con éxito!",
                    "Éxito",
                    JOptionPane.INFORMATION_MESSAGE);

            mostrarBoletaVenta(ventaGuardada);
            limpiarFormularioVenta();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Error al procesar la venta: " + e.getMessage(),
                    "Error de BD",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnProcesarVentaActionPerformed

