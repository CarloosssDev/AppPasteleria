    private void agregarProductoAlCarrito() {
        int filaSeleccionada = tblProductos.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this,
                    "Por favor, seleccione un producto del catálogo.",
                    "Advertencia",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int cantidad = (Integer) spnCantidad.getValue();
        if (cantidad <= 0) {
            JOptionPane.showMessageDialog(this,
                    "La cantidad debe ser mayor a 0.",
                    "Cantidad Inválida",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        Long idProducto = Long.parseLong(tblProductos.getValueAt(filaSeleccionada, 0).toString());
        String nombre = tblProductos.getValueAt(filaSeleccionada, 1).toString();

        String precioStr = tblProductos.getValueAt(filaSeleccionada, 2).toString().replace("S/ ", "").replace(",", ".");
        double precio = Double.parseDouble(precioStr);

        int stockDisponible = Integer.parseInt(tblProductos.getValueAt(filaSeleccionada, 3).toString());

        if (cantidad > stockDisponible) {
            JOptionPane.showMessageDialog(this,
                    "Stock insuficiente. Solo quedan " + stockDisponible + " unidades disponibles.",
                    "Stock Insuficiente",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        boolean existe = false;
        for (int i = 0; i < modeloCarrito.getRowCount(); i++) {
            Long idEnCarrito = Long.parseLong(modeloCarrito.getValueAt(i, 0).toString());
            if (idEnCarrito.equals(idProducto)) {
                int cantidadActual = Integer.parseInt(modeloCarrito.getValueAt(i, 2).toString());
                int nuevaCantidad = cantidadActual + cantidad;

                if (nuevaCantidad > stockDisponible) {
                    JOptionPane.showMessageDialog(this,
                            "No puede agregar más unidades. Supera el stock disponible (" + stockDisponible + ").",
                            "Stock Superado",
                            JOptionPane.WARNING_MESSAGE);
                    return;
                }

                double nuevoSubtotal = nuevaCantidad * precio;
                modeloCarrito.setValueAt(nuevaCantidad, i, 2);
                modeloCarrito.setValueAt(String.format("S/ %.2f", nuevoSubtotal), i, 4);
                existe = true;
                break;
            }
        }

        if (!existe) {
            double subtotal = cantidad * precio;
            Object[] fila = new Object[]{
                idProducto,
                nombre,
                cantidad,
                String.format("S/ %.2f", precio),
                String.format("S/ %.2f", subtotal)
            };
            modeloCarrito.addRow(fila);
        }

        calcularTotalesVenta();
        spnCantidad.setValue(1);
    }

    private void calcularTotalesVenta() {
        double total = 0.0;

        for (int i = 0; i < modeloCarrito.getRowCount(); i++) {
            String subtotalStr = modeloCarrito.getValueAt(i, 4).toString().replace("S/ ", "").replace(",", ".");
            total += Double.parseDouble(subtotalStr);
        }

        double subtotalNeto = total / 1.18;

        lblSubtotal.setText(String.format("S/ %.2f", subtotalNeto));
        lblTotal.setText(String.format("S/ %.2f", total));

        recalcularSaldo();
    }

    private void recalcularSaldo() {
        try {
            String totalStr = lblTotal.getText().replace("S/ ", "").replace(",", ".");
            double total = Double.parseDouble(totalStr);

            String adelantoStr = txtAdelanto.getText().trim().replace(",", ".");
            double adelanto = adelantoStr.isEmpty() ? 0.0 : Double.parseDouble(adelantoStr);

            double diferencia = total - adelanto;

            if (diferencia < 0) {
                double vuelto = Math.abs(diferencia);
                lblSaldo.setText(String.format("Vuelto: S/ %.2f", vuelto));
                lblSaldo.setForeground(new java.awt.Color(0, 153, 76));
            } else if (diferencia > 0) {
                lblSaldo.setText(String.format("Saldo: S/ %.2f", diferencia));
                lblSaldo.setForeground(java.awt.Color.RED);
            } else {
                lblSaldo.setText("S/ 0.00");
                lblSaldo.setForeground(java.awt.Color.BLACK);
            }
        } catch (NumberFormatException e) {
            lblSaldo.setText("S/ 0.00");
            lblSaldo.setForeground(java.awt.Color.BLACK);
        }
    }

