    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String nombre = txtNombre.getText().trim();
        String descripcion = txtDescripcion.getText().trim();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre de la categoría es obligatorio.",
                    "Validación", JOptionPane.WARNING_MESSAGE);
            txtNombre.requestFocus();
            return;
        }

        try {
            Categoria cat;
            if (esEdicion) {
                Long id = Long.parseLong(txtId.getText());
                cat = service.buscarPorId(id);
            } else {
                cat = new Categoria();
            }

            cat.setNombre(nombre);
            cat.setDescripcion(descripcion);
            cat.setEstado(cbEstado.isSelected());

            service.guardar(cat);

            JOptionPane.showMessageDialog(this,
                    esEdicion ? "Categoría actualizada correctamente." : "Categoría registrada correctamente.");
            aplicarFiltrosCombinados();
            estadoInicialFormulario();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar la categoría: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int fila = tblCartegorias.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione una categoría de la tabla.",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Long idCategoria = (Long) tblCartegorias.getValueAt(fila, 0);
        cargarCategoriaEnFormulario(idCategoria);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblCartegorias.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione una categoría de la tabla para desactivar.",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Long idCategoria = (Long) tblCartegorias.getValueAt(fila, 0);
        String nombreCat = (String) tblCartegorias.getValueAt(fila, 1);

        int confirmacion = JOptionPane.showConfirmDialog(this,
                "¿Está seguro de desactivar la categoría \"" + nombreCat + "\"?",
                "Confirmar Desactivación", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);

        if (confirmacion == JOptionPane.YES_OPTION) {
            try {
                service.eliminarLogico(idCategoria);
                JOptionPane.showMessageDialog(this, "Categoría desactivada correctamente.");
                aplicarFiltrosCombinados();
                estadoInicialFormulario();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al desactivar la categoría: " + e.getMessage(),
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

