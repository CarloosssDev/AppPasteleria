    private void cargarTodasLasCategorias() {
        try {
            List<Categoria> lista = service.listarTodas();
            llenarTablaCategorias(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al filtrar categorias: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void llenarTablaCategorias(List<Categoria> list) {
        modeloCategorias.setRowCount(0);

        for (Categoria c : list) {
            Object[] fila = new Object[]{
                c.getId(),
                c.getNombre(),
                c.getDescripcion(),
                c.isEstado() ? "Activo" : "Inactivo"
            };
            modeloCategorias.addRow(fila);
        }

    }

    private void configurarTablaCategorias() {
        String[] columnas = {"ID", "Nombre", "Descripción", "Estado"};
        modeloCategorias = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblCartegorias.setModel(modeloCategorias);
    }

    private void aplicarFiltrosCombinados() {
        try {
            Boolean estado = null;
            int indexEstado = cboEstado.getSelectedIndex();
            if (indexEstado == 1) {
                estado = true;
            } else if (indexEstado == 2) {
                estado = false;
            }

            String texto = txtBuscar.getText().trim();
            List<Categoria> lista = service.filtrarCategorias(estado, texto);
            llenarTablaCategorias(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al filtrar categorías: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void cargarCategoriaEnFormulario(Long idCategoria) {
        try {
            Categoria c = service.buscarPorId(idCategoria);

            if (c != null) {
                txtId.setText(String.valueOf(c.getId()));
                txtNombre.setText(c.getNombre());
                txtDescripcion.setText(c.getDescripcion());
                cbEstado.setSelected(c.isEstado());
                esEdicion = true;
                habilitarFormulario(true);
                txtNombre.requestFocus();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al obtener datos de la categoria: " + e.getMessage());
        }
    }

    private void limpiarFormulario() {
        txtId.setText("");
        txtNombre.setText("");
        txtDescripcion.setText("");
        cbEstado.setSelected(true);
    }

    private void habilitarFormulario(boolean habilitar) {
        txtNombre.setEnabled(habilitar);
        txtDescripcion.setEnabled(habilitar);
        cbEstado.setEnabled(habilitar);

        btnGuardar.setEnabled(habilitar);
        btnCancelar.setEnabled(habilitar);

        btnNuevo.setEnabled(!habilitar);
        btnEditar.setEnabled(!habilitar);
        btnEliminar.setEnabled(!habilitar);
        tblCartegorias.setEnabled(!habilitar);
    }

    private void estadoInicialFormulario() {
        limpiarFormulario();
        habilitarFormulario(false);
        esEdicion = false;
    }

