    private void consultarVentasPorRangoFechas() {
        try {
            Date dateInicio = dtcFechaInicio.getDate();
            Date dateFin = dtcFechaFin.getDate();

            if (dateInicio == null || dateFin == null) {
                JOptionPane.showMessageDialog(this, "Debe seleccionar ambas fechas.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }

            LocalDate fInicio = dateInicio.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
            LocalDate fFin = dateFin.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();

            if (fInicio.isAfter(fFin)) {
                JOptionPane.showMessageDialog(this, "La fecha inicio no puede ser posterior a la fecha fin.", "Validación", JOptionPane.WARNING_MESSAGE);
                return;
            }

            listaVentasActuales = ventaService.buscarVentasPorFecha(fInicio, fFin);
            llenarTablaVentas(listaVentasActuales);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al consultar ventas: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void cargarTodasLasVentas() {
        try {
            listaVentasActuales = ventaService.listarTodas();
            llenarTablaVentas(listaVentasActuales);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al listar ventas: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void llenarTablaVentas(List<Venta> lista) {
        modeloVentas.setRowCount(0);
        double totalAcumulado = 0.0;

        for (Venta v : lista) {
            String cliente = (v.getCliente() != null) ? v.getCliente().mostrarNombreCompleto() : "Cliente Varios";
            String empleado = (v.getEmpleado() != null) ? v.getEmpleado().mostrarNombreCompleto() : "Cajero";
            String fechaStr = (v.getFecha() != null) ? v.getFecha().format(formatter) : "---";

            Object[] fila = new Object[]{
                v.getId(),
                fechaStr,
                cliente,
                empleado,
                String.format("S/ %.2f", v.getTotal()),
                String.format("S/ %.2f", v.getAdelanto()),
                String.format("S/ %.2f", v.getSaldo())
            };
            modeloVentas.addRow(fila);
            totalAcumulado += v.getTotal();
        }

        lblTotalAcumulado.setText(String.format("S/ %.2f", totalAcumulado));
    }

    private void verComprobanteSeleccionado() {
        int fila = tblVentas.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una venta de la tabla.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Long idVenta = Long.parseLong(tblVentas.getValueAt(fila, 0).toString());

        Venta venta = listaVentasActuales.stream()
                .filter(v -> v.getId().equals(idVenta))
                .findFirst()
                .orElse(null);

        if (venta != null) {
            String html = GeneradorBoleta.generarHtmlBoletaDesdeEntidad(venta);

            javax.swing.JEditorPane visor = new javax.swing.JEditorPane();
            visor.setContentType("text/html");
            visor.setText(html);
            visor.setEditable(false);
            visor.setCaretPosition(0);

            javax.swing.JScrollPane scroll = new javax.swing.JScrollPane(visor);
            scroll.setPreferredSize(new java.awt.Dimension(380, 500));

            JOptionPane.showMessageDialog(this, scroll, "Boleta de Venta N° " + venta.getId(), JOptionPane.PLAIN_MESSAGE);
        }
    }
