    private void configurarTablaClientes() {
        String[] columnas = {"ID", "DNI", "Nombre Completo", "Teléfono", "Correo", "Estado"};
        modeloClientes = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblClientes.setModel(modeloClientes);
    }

    private void cargarTodosLosClientes() {
        try {
            List<Cliente> lista = service.listarTodos();
            llenarTablaClientes(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar clientes: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void aplicarFiltrosCombinados() {
        try {
            Boolean estado = null;
            int indexEstado = cboEstado.getSelectedIndex();
            if (indexEstado == 1) {
                estado = true;
            } else if (indexEstado == 2) {
                estado = false;
            }

            String texto = txtBuscar.getText().trim();
            List<Cliente> lista = service.filtrarClientes(estado, texto);
            llenarTablaClientes(lista);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al filtrar clientes: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void llenarTablaClientes(List<Cliente> lista) {
        modeloClientes.setRowCount(0);

        for (Cliente c : lista) {
            Object[] fila = new Object[]{
                c.getId(),
                c.getDni(),
                c.mostrarNombreCompleto(),
                c.getTelefono() != null ? c.getTelefono() : "",
                c.getEmail() != null ? c.getEmail() : "",
                c.isEstado() ? "Activo" : "Inactivo"
            };
            modeloClientes.addRow(fila);
        }
    }

    private void cargarClienteEnFormulario(Long idCliente) {
        try {
            Cliente c = service.buscarPorId(idCliente);
            if (c != null) {
                txtId.setText(String.valueOf(c.getId()));
                txtDni.setText(c.getDni());
                txtNombre.setText(c.getNombre());
                txtApellido.setText(c.getApellido());
                txtTelefono.setText(c.getTelefono() != null ? c.getTelefono() : "");
                txtCorreo.setText(c.getEmail() != null ? c.getEmail() : "");
                cbEstado.setSelected(c.isEstado());

                esEdicion = true;
                habilitarFormulario(true);
                txtDni.requestFocus();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al obtener datos del cliente: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpiarFormulario() {
        txtId.setText("");
        txtDni.setText("");
        txtNombre.setText("");
        txtApellido.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        cbEstado.setSelected(true);
    }

    private void habilitarFormulario(boolean habilitar) {
        txtDni.setEnabled(habilitar);
        txtNombre.setEnabled(habilitar);
        txtApellido.setEnabled(habilitar);
        txtTelefono.setEnabled(habilitar);
        txtCorreo.setEnabled(habilitar);
        cbEstado.setEnabled(habilitar);

        btnGuardar.setEnabled(habilitar);
        btnCancelar.setEnabled(habilitar);

        btnNuevo.setEnabled(!habilitar);
        btnEditar.setEnabled(!habilitar);
        btnEliminar.setEnabled(!habilitar);
        tblClientes.setEnabled(!habilitar);
    }

    private void estadoInicialFormulario() {
        limpiarFormulario();
        habilitarFormulario(false);
        esEdicion = false;
    }

