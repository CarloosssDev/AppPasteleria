    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String dni = txtDni.getText().trim();
        String nombres = txtNombre.getText().trim();
        String apellidos = txtApellido.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String correo = txtCorreo.getText().trim();

        if (!dni.matches("\\d{8}")) {
            JOptionPane.showMessageDialog(this, "El DNI debe contener exactamente 8 dígitos numéricos.",
                    "Validación", JOptionPane.WARNING_MESSAGE);
            txtDni.requestFocus();
            return;
        }

        if (nombres.isEmpty() || apellidos.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Los nombres y apellidos del cliente son obligatorios.",
                    "Validación", JOptionPane.WARNING_MESSAGE);
            txtNombre.requestFocus();
            return;
        }
        if (!telefono.isEmpty() && !telefono.matches("^9\\d{8}$")) {
            JOptionPane.showMessageDialog(this,
                    "El teléfono debe tener 9 dígitos numéricos y empezar con 9 (ej: 987654321).",
                    "Validación", JOptionPane.WARNING_MESSAGE);
            txtTelefono.requestFocus();
            return;
        }

        if (!correo.isEmpty() && !correo.matches("^[\\w.-]+@[\\w.-]+\\.[a-zA-Z]{2,}$")) {
            JOptionPane.showMessageDialog(this, "Ingrese un correo electrónico válido.",
                    "Validación", JOptionPane.WARNING_MESSAGE);
            txtCorreo.requestFocus();
            return;
        }

        try {
            Cliente cliente;
            if (esEdicion) {
                Long id = Long.parseLong(txtId.getText());
                cliente = service.buscarPorId(id);
            } else {
                cliente = new Cliente();
            }

            cliente.setDni(dni);
            cliente.setNombre(nombres);
            cliente.setApellido(apellidos);
            cliente.setTelefono(telefono);
            cliente.setEmail(correo);
            cliente.setEstado(cbEstado.isSelected());

            service.guardar(cliente);

            JOptionPane.showMessageDialog(this,
                    esEdicion ? "Cliente actualizado correctamente." : "Cliente registrado correctamente.");
            aplicarFiltrosCombinados();
            estadoInicialFormulario();

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Validación", JOptionPane.WARNING_MESSAGE);
            txtDni.requestFocus();
        } catch (Exception e) {
            Throwable causa = e;
            while (causa.getCause() != null) {
                causa = causa.getCause();
            }
            e.printStackTrace();
            JOptionPane.showMessageDialog(this,
                    "Error al guardar el cliente:\n" + causa.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int fila = tblClientes.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione un cliente de la tabla.",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Long idCliente = (Long) tblClientes.getValueAt(fila, 0);
        cargarClienteEnFormulario(idCliente);
    }//GEN-LAST:event_btnEditarActionPerformed

